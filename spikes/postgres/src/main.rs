//! THROWAWAY SPIKE (06 §2A). Answers PostgreSQL and SQLx questions on a
//! disposable database. Not production code: nothing here is reused, and the
//! schema below is not the production schema. Delete once findings are recorded.
//!
//! Run only against the local compose PostgreSQL: it creates a scratch
//! database and a few uniquely named roles, then drops them, even when a
//! check fails.
//!
//! SQL strings: SQLx 0.9 accepts only `&'static str`. The few statements here
//! that embed identifiers (database and role names) are wrapped in
//! `AssertSqlSafe` one by one, each marked at its call site; the identifiers
//! are generated by this program from a random hex tag, never taken from input.

use std::{str::FromStr, time::Duration};

use sqlx::{
    AssertSqlSafe, Connection, Executor, PgConnection,
    postgres::{PgConnectOptions, PgPoolOptions},
};
use uuid::Uuid;

type Res<T> = Result<T, Box<dyn std::error::Error>>;

#[tokio::main]
async fn main() -> Res<()> {
    dotenvy::from_path(concat!(env!("CARGO_MANIFEST_DIR"), "/../../.env")).ok();
    let admin_url = std::env::var("DATABASE_URL")?;
    let admin_opts = PgConnectOptions::from_str(&admin_url)?;
    // It creates and force-drops databases and cluster-wide roles: refuse
    // anything but a server on this machine (the local compose cluster).
    let host = admin_opts.get_host();
    if !matches!(host, "127.0.0.1" | "localhost" | "::1" | "[::1]") {
        return Err(format!(
            "refusing to run: DATABASE_URL host is {host:?}; this spike only runs against a local disposable cluster"
        )
        .into());
    }

    let tag = Uuid::new_v4().simple().to_string()[..8].to_owned();
    let db = format!("scanpay_spike_{tag}");
    let roles = Roles::new(&tag);

    let mut admin = PgConnection::connect_with(&admin_opts).await?;
    // AssertSqlSafe: `db` is spike-generated (fixed prefix + hex tag).
    sqlx::raw_sql(AssertSqlSafe(format!("CREATE DATABASE {db}")))
        .execute(&mut admin)
        .await?;
    let spike_opts = admin_opts.clone().database(&db);

    let outcome = run(&spike_opts, &roles).await;
    if let Err(e) = &outcome {
        eprintln!("\nspike stopped early: {e}");
    }

    // Cleanup always runs and tries every step, whatever happened above.
    let mut cleanup_failed = false;
    // AssertSqlSafe: `db` is spike-generated.
    let drop_db = format!("DROP DATABASE IF EXISTS {db} WITH (FORCE)");
    if let Err(e) = sqlx::raw_sql(AssertSqlSafe(drop_db)).execute(&mut admin).await {
        eprintln!("could not drop {db}: {e}");
        cleanup_failed = true;
    }
    for role in roles.all() {
        // AssertSqlSafe: role names are spike-generated.
        let drop_role = format!("DROP ROLE IF EXISTS {role}");
        if let Err(e) = sqlx::raw_sql(AssertSqlSafe(drop_role)).execute(&mut admin).await {
            eprintln!("could not drop role {role}: {e}");
            cleanup_failed = true;
        }
    }
    if cleanup_failed {
        eprintln!("cleanup incomplete: drop the objects above by hand");
    } else {
        println!("\ncleaned up {db} and spike roles");
    }
    outcome
}

struct Roles {
    producer: String,
    contract: String,
    reader: String,
}

impl Roles {
    fn new(tag: &str) -> Self {
        Self {
            producer: format!("spike_producer_{tag}"),
            contract: format!("spike_contract_{tag}"),
            reader: format!("spike_reader_{tag}"),
        }
    }

    fn all(&self) -> [&str; 3] {
        [&self.producer, &self.contract, &self.reader]
    }
}

async fn run(opts: &PgConnectOptions, roles: &Roles) -> Res<()> {
    let pool = PgPoolOptions::new()
        .max_connections(2)
        .connect_with(opts.clone())
        .await?;
    let version: String = sqlx::query_scalar("SHOW server_version")
        .fetch_one(&pool)
        .await?;
    println!("PostgreSQL {version}\n");

    q1_tenant_setting_scope(opts).await?;
    q2_rls_through_owner_view(opts, roles).await?;
    q3_transaction_timeout(opts).await?;
    q4_sqlstate_mapping(opts).await?;
    q5_lost_connection(opts).await?;
    Ok(())
}

/// Q1: does set_config(..., true) behave like SET LOCAL, and what does
/// current_setting(..., true) return after the transaction ends?
async fn q1_tenant_setting_scope(opts: &PgConnectOptions) -> Res<()> {
    let mut conn = PgConnection::connect_with(opts).await?;
    let before: Option<String> =
        sqlx::query_scalar("SELECT current_setting('app.organization_id', true)")
            .fetch_one(&mut conn)
            .await?;

    let org = Uuid::new_v4().to_string();
    let mut tx = conn.begin().await?;
    sqlx::query("SELECT set_config('app.organization_id', $1, true)")
        .bind(&org)
        .execute(&mut *tx)
        .await?;
    let inside: Option<String> =
        sqlx::query_scalar("SELECT current_setting('app.organization_id', true)")
            .fetch_one(&mut *tx)
            .await?;
    tx.commit().await?;

    let after: Option<String> =
        sqlx::query_scalar("SELECT current_setting('app.organization_id', true)")
            .fetch_one(&mut conn)
            .await?;

    println!("Q1 tenant setting scope");
    println!("  before any set:      {before:?}");
    println!("  inside transaction:  matches = {}", inside.as_deref() == Some(org.as_str()));
    println!("  after commit:        {after:?}");
    println!("  => policies must treat both NULL and '' as 'no tenant'\n");
    Ok(())
}

/// Q2: row-level security read through an owner-privilege contract view.
async fn q2_rls_through_owner_view(opts: &PgConnectOptions, r: &Roles) -> Res<()> {
    let mut su = PgConnection::connect_with(opts).await?;
    let (producer, contract, reader) = (&r.producer, &r.contract, &r.reader);
    // AssertSqlSafe: role names are spike-generated; everything else is literal.
    let ddl = format!(
            "CREATE ROLE {producer} NOLOGIN;
             CREATE ROLE {contract} NOLOGIN;
             CREATE ROLE {reader} NOLOGIN;
             CREATE SCHEMA spike_org;
             GRANT USAGE ON SCHEMA spike_org TO {producer}, {contract}, {reader};
             CREATE TABLE spike_org.members (organization_id uuid NOT NULL, name text NOT NULL);
             ALTER TABLE spike_org.members OWNER TO {producer};
             ALTER TABLE spike_org.members ENABLE ROW LEVEL SECURITY;
             ALTER TABLE spike_org.members FORCE ROW LEVEL SECURITY;
             CREATE POLICY tenant ON spike_org.members
               USING (organization_id = nullif(current_setting('app.organization_id', true), '')::uuid);
             GRANT SELECT ON spike_org.members TO {contract};
             CREATE VIEW spike_org.members_v1 AS SELECT organization_id, name FROM spike_org.members;
             ALTER VIEW spike_org.members_v1 OWNER TO {contract};
             GRANT SELECT ON spike_org.members_v1 TO {reader};"
    );
    sqlx::raw_sql(AssertSqlSafe(ddl)).execute(&mut su).await?;

    let (a, b) = (Uuid::new_v4(), Uuid::new_v4());
    for (org, name) in [(a, "a1"), (a, "a2"), (b, "b1")] {
        sqlx::query("INSERT INTO spike_org.members VALUES ($1, $2)")
            .bind(org)
            .bind(name)
            .execute(&mut su)
            .await?;
    }

    println!("Q2 RLS through owner-privilege view (FORCE RLS, view owned by a non-owner role)");
    for (label, role, org, sql) in [
        ("reader, org A, view", reader, Some(a), "SELECT count(*) FROM spike_org.members_v1"),
        ("reader, org B, view", reader, Some(b), "SELECT count(*) FROM spike_org.members_v1"),
        ("reader, no setting, view", reader, None, "SELECT count(*) FROM spike_org.members_v1"),
        ("reader, org A, base table", reader, Some(a), "SELECT count(*) FROM spike_org.members"),
        ("producer (owner), no setting, base", producer, None, "SELECT count(*) FROM spike_org.members"),
        ("producer (owner), org A, base", producer, Some(a), "SELECT count(*) FROM spike_org.members"),
    ] {
        let mut tx = su.begin().await?;
        // AssertSqlSafe: `role` is spike-generated.
        sqlx::raw_sql(AssertSqlSafe(format!("SET LOCAL ROLE {role}")))
            .execute(&mut *tx)
            .await?;
        if let Some(org) = org {
            sqlx::query("SELECT set_config('app.organization_id', $1, true)")
                .bind(org.to_string())
                .execute(&mut *tx)
                .await?;
        }
        let result: Result<i64, _> = sqlx::query_scalar(sql).fetch_one(&mut *tx).await;
        match result {
            Ok(n) => println!("  {label:<36} rows = {n}"),
            Err(e) => println!("  {label:<36} error {}", sqlstate(&e)),
        }
        tx.rollback().await?;
    }
    println!("  (expected: A=2, B=1, none=0, base table denied 42501, owner none=0, owner A=2)\n");
    Ok(())
}

/// Q3: PostgreSQL 17 transaction_timeout set with SET LOCAL mid-transaction.
async fn q3_transaction_timeout(opts: &PgConnectOptions) -> Res<()> {
    println!("Q3 transaction_timeout (SET LOCAL mid-transaction)");
    let mut conn = PgConnection::connect_with(opts).await?;
    let supported: Result<String, _> = sqlx::query_scalar("SHOW transaction_timeout")
        .fetch_one(&mut conn)
        .await;
    if let Err(e) = supported {
        println!("  not supported on this server: {}\n", sqlstate(&e));
        return Ok(());
    }

    conn.execute("BEGIN").await?;
    conn.execute("SELECT pg_sleep(0.4)").await?;
    conn.execute("SET LOCAL transaction_timeout = '600ms'").await?;
    let early = conn.execute("SELECT pg_sleep(0.4)").await;
    println!(
        "  0.4s before SET + 0.4s after a 600ms timeout: {}",
        match &early {
            Ok(_) => "no timeout => counts from the SET, not BEGIN".to_owned(),
            Err(e) => format!("timed out ({}) => counts from BEGIN", sqlstate(e)),
        }
    );
    if early.is_ok() {
        let late = conn.execute("SELECT pg_sleep(1)").await;
        match late {
            Ok(_) => println!("  1s more: no timeout (unexpected)"),
            Err(e) => println!("  1s more: error {} ({})", sqlstate(&e), short(&e)),
        }
    }
    let after = conn.execute("SELECT 1").await;
    println!(
        "  same connection afterwards: {}",
        match after {
            Ok(_) => "still usable".to_owned(),
            Err(e) => format!("unusable ({}) => session ended; treat as unknown outcome", short(&e)),
        }
    );
    println!();
    Ok(())
}

/// Q4: which SQLSTATE does SQLx surface for each error class?
async fn q4_sqlstate_mapping(opts: &PgConnectOptions) -> Res<()> {
    println!("Q4 SQLSTATE as seen through sqlx::Error");
    let mut conn = PgConnection::connect_with(opts).await?;
    for (code, sql) in [
        ("40001", "DO $$ BEGIN RAISE EXCEPTION 'spike' USING ERRCODE = '40001'; END $$"),
        ("40P01", "DO $$ BEGIN RAISE EXCEPTION 'spike' USING ERRCODE = '40P01'; END $$"),
        ("57014", "DO $$ BEGIN RAISE EXCEPTION 'spike' USING ERRCODE = '57014'; END $$"),
        ("55P03", "DO $$ BEGIN RAISE EXCEPTION 'spike' USING ERRCODE = '55P03'; END $$"),
        ("25P04", "DO $$ BEGIN RAISE EXCEPTION 'spike' USING ERRCODE = '25P04'; END $$"),
        ("23505", "DO $$ BEGIN RAISE EXCEPTION 'spike' USING ERRCODE = '23505'; END $$"),
    ] {
        expect_error(&format!("raised {code}"), conn.execute(sql).await);
    }
    conn.execute("SET statement_timeout = '50ms'").await?;
    expect_error("real statement_timeout", conn.execute("SELECT pg_sleep(1)").await);
    println!();
    Ok(())
}

/// Prints the error an operation was expected to produce, without panicking
/// (a panic would skip cleanup) if it unexpectedly succeeds.
fn expect_error<T>(label: &str, result: Result<T, sqlx::Error>) {
    match result {
        Err(e) => println!("  {label}: {} ({})", sqlstate(&e), kind(&e)),
        Ok(_) => println!("  {label}: no error (unexpected)"),
    }
}

/// Q5: what does SQLx report when the server kills the connection mid-use?
async fn q5_lost_connection(opts: &PgConnectOptions) -> Res<()> {
    println!("Q5 lost connection");
    let mut victim = PgConnection::connect_with(opts).await?;
    let pid: i32 = sqlx::query_scalar("SELECT pg_backend_pid()")
        .fetch_one(&mut victim)
        .await?;
    let mut killer = PgConnection::connect_with(opts).await?;
    victim.execute("BEGIN").await?;
    sqlx::query("SELECT pg_terminate_backend($1)")
        .bind(pid)
        .execute(&mut killer)
        .await?;
    tokio::time::sleep(Duration::from_millis(200)).await;
    expect_error("next query on terminated session", victim.execute("SELECT 1").await);
    println!("  => classify as connection lost: outcome unknown, check the command key\n");
    Ok(())
}

fn sqlstate(e: &sqlx::Error) -> String {
    e.as_database_error()
        .and_then(|d| d.code().map(|c| format!("SQLSTATE {c}")))
        .unwrap_or_else(|| format!("no SQLSTATE ({})", kind(e)))
}

fn kind(e: &sqlx::Error) -> &'static str {
    match e {
        sqlx::Error::Database(_) => "Error::Database",
        sqlx::Error::Io(_) => "Error::Io",
        sqlx::Error::Protocol(_) => "Error::Protocol",
        sqlx::Error::PoolClosed => "Error::PoolClosed",
        sqlx::Error::PoolTimedOut => "Error::PoolTimedOut",
        _ => "other sqlx::Error",
    }
}

fn short(e: &sqlx::Error) -> String {
    let s = e.to_string();
    s.chars().take(90).collect()
}
